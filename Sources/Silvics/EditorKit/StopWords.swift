import Foundation

/// 提及匹配用的停用词表（设计文档 3.3 门槛 2）。
///
/// 只收中文功能词与泛谓词。名字整体等于表中一项时不上报。
/// 表内一律写归一化形式（小写、半角）。
enum StopWords {

    static let all: Set<String> = [
        // 连词、介词、语气
        "因为", "所以", "但是", "然后", "而且", "或者", "如果", "虽然", "因此",
        "由于", "于是", "并且", "以及", "对于", "关于", "根据", "通过", "为了",
        "即使", "除非", "否则", "同时", "另外", "此外", "总之", "比如", "例如",
        // 代词、指代
        "我们", "你们", "他们", "她们", "它们", "自己", "大家", "别人", "这个",
        "那个", "这些", "那些", "这样", "那样", "这里", "那里", "什么", "怎么",
        "为什么", "哪个", "哪些",
        // 泛谓词与判断
        "就是", "还是", "不是", "没有", "可以", "需要", "应该", "必须", "已经",
        "正在", "曾经", "还没", "不能", "不会", "不要", "可能", "一定", "也许",
        "其实", "确实", "当然", "比较", "非常", "特别", "尤其", "更加", "最好",
        // 数量与时间
        "一个", "一些", "一下", "一点", "很多", "许多", "所有", "全部", "部分",
        "时候", "时间", "现在", "以后", "以前", "今天", "明天", "昨天", "最近",
        // 泛名词
        "问题", "事情", "东西", "地方", "方法", "方式", "情况", "内容", "部分",
        "方面", "结果", "过程", "原因", "意思", "想法", "感觉", "关系", "作用",
        // 笔记应用里常见但无信息量的词
        "笔记", "记录", "总结", "整理", "回顾",
    ]

    static func contains(_ normalizedName: String) -> Bool {
        all.contains(normalizedName)
    }
}
